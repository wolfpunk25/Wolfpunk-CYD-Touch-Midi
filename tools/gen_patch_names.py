#!/usr/bin/env python3
"""Generate CYDMidi/patch_names.h from the Pi's patch library.

Usage: tools/gen_patch_names.py [patches.json]   (default: fetched from pi4.local)

Program number sent by the controller = patch id number - 1 (id "p5" -> program 4),
so it stays stable when you reorder the setlist. Ids above p128 can't be addressed.
"""
import json, subprocess, sys, os

if len(sys.argv) > 1:
    data = json.load(open(sys.argv[1]))
else:
    out = subprocess.run(["ssh", "-o", "BatchMode=yes", "darren@pi4.local",
                          "cat /var/lib/pitop-synth/patches.json"],
                         check=True, capture_output=True, text=True).stdout
    data = json.loads(out)

names = {}
for p in data["patches"]:
    pid = p["id"]
    if pid[:1] == "p" and pid[1:].isdigit() and 1 <= int(pid[1:]) <= 128:
        names[int(pid[1:]) - 1] = p["name"]

dest = os.path.join(os.path.dirname(__file__), "..", "CYDMidi", "patch_names.h")
with open(dest, "w") as f:
    f.write("// Generated by tools/gen_patch_names.py - do not edit by hand.\n")
    f.write("#ifndef PATCH_NAMES_H\n#define PATCH_NAMES_H\n\n")
    f.write("struct PatchEntry { uint8_t program; const char *name; };\n")
    f.write("const PatchEntry PATCH_LIST[] = {\n")
    for prog in sorted(names):
        name = names[prog].encode("ascii", "replace").decode().replace('"', "'")[:18]
        f.write(f'  {{{prog}, "{name}"}},\n')
    f.write("};\n")
    f.write(f"const int PATCH_COUNT = {len(names)};\n\n#endif\n")
print(f"wrote {len(names)} patches to {os.path.normpath(dest)}")
